const a = (key) => TEXT[lang][key] || key
function esc(value) {
  return String(value ?? "").replace(/[&<>"']/g, (char) => ({
    "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;",
  }[char]))
}
function iso(date) {
  const month = String(date.getMonth() + 1).padStart(2, "0")
  const day = String(date.getDate()).padStart(2, "0")
  return `${date.getFullYear()}-${month}-${day}`
}
function startOfMonth(date) {
  return new Date(date.getFullYear(), date.getMonth(), 1)
}
function monthEnd(date) {
  return iso(new Date(date.getFullYear(), date.getMonth() + 1, 0))
}
function money(value) {
  if (value == null || value === "") return "—"
  return `₹${new Intl.NumberFormat("en-IN").format(value)}`
}
function serviceName(id) {
  const service = services.find((item) => item.id === id)
  if (!service) return id
  return lang === "hi" ? service.name_hi : service.name_en
}
function slotName(id) {
  const slot = slots.find((item) => item.id === id)
  if (!slot) return id
  const label = lang === "hi" ? slot.label_hi : slot.label_en
  return `${label} ${slot.starts}–${slot.ends}`
}
function toast(message, bad) {
  const node = $("#toast")
  node.textContent = message
  node.hidden = false
  node.classList.toggle("is-bad", Boolean(bad))
  clearTimeout(toast.timer)
  toast.timer = setTimeout(() => { node.hidden = true }, 3200)
}
function fail(error) {
  const message = String(error?.message || "")
  if (message.includes("duplicate") || message.includes("tag_no")) return toast(a("duplicate"), true)
  if (message.includes("slot") || message.includes("bookings_open_slot")) return toast(a("taken"), true)
  return toast(a("failed"), true)
}
function numOrNull(value) {
  if (value === "" || value == null) return null
  const number = Number(value)
  return Number.isFinite(number) ? number : null
}

