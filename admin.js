function formData(form) {
  return Object.fromEntries(new FormData(form).entries())
}

async function compress(file) {
  if (!file || !file.size) return ""
  const url = URL.createObjectURL(file)
  try {
    const image = await new Promise((resolve, reject) => {
      const node = new Image()
      node.onload = () => resolve(node)
      node.onerror = reject
      node.src = url
    })
    const scale = Math.min(1, 900 / Math.max(image.width, image.height))
    const canvas = document.createElement("canvas")
    canvas.width = Math.max(1, Math.round(image.width * scale))
    canvas.height = Math.max(1, Math.round(image.height * scale))
    canvas.getContext("2d").drawImage(image, 0, 0, canvas.width, canvas.height)
    const data = canvas.toDataURL("image/jpeg", 0.72)
    if (data.length > 180000) throw new Error("photo")
    return data
  } finally {
    URL.revokeObjectURL(url)
  }
}

async function onSubmit(event) {
  const form = event.target
  if (!(form instanceof HTMLFormElement)) return
  event.preventDefault()
  const kind = form.dataset.form
  const data = formData(form)
  try {
    if (kind === "booking") {
      const { error } = await db.from("bookings").update({
        status: data.status,
        paid_status: data.paid_status,
        amount_inr: numOrNull(data.amount_inr),
      }).eq("id", form.dataset.id)
      if (error) return fail(error)
    }
    if (kind === "walkin") {
      const phone = data.phone.replace(/\D/g, "")
      if (!/^[6-9]\d{9}$/.test(phone)) return toast(a("failed"), true)
      if (blocks.some((item) => item.event_date === selected && item.slot === data.slot)) return toast(a("taken"), true)
      const service = services.find((item) => item.id === data.service_id)
      const { error } = await db.from("bookings").insert({
        category: service?.category || "salon",
        service_id: data.service_id,
        event_date: selected,
        slot: data.slot,
        customer_name: data.customer_name.trim(),
        phone,
        guest_for: data.guest_for,
        note: data.note || "",
        status: "confirmed",
        paid_status: data.paid_status,
        amount_inr: numOrNull(data.amount_inr),
      })
      if (error) return fail(error)
    }
    if (kind === "service-edit" || kind === "service-new") {
      const payload = {
        name_hi: data.name_hi.trim(),
        name_en: data.name_en.trim(),
        note_hi: data.note_hi || "",
        note_en: data.note_en || "",
        price_inr: numOrNull(data.price_inr),
        group_key: data.group_key,
        category: data.category,
        active: form.querySelector('[name="active"]').checked,
        updated_at: new Date().toISOString(),
      }
      const query = kind === "service-edit"
        ? db.from("services").update(payload).eq("id", form.dataset.id)
        : db.from("services").insert({ ...payload, id: `custom-${Date.now()}`, sort_order: 900 })
      const { error } = await query
      if (error) return fail(error)
    }
    if (kind === "lehenga-new" || kind === "lehenga-edit") {
      let photo = ""
      const file = form.querySelector('[name="photo"]')?.files?.[0]
      if (file) {
        try { photo = await compress(file) } catch { return toast(a("photoBig"), true) }
      }
      if (kind === "lehenga-new") {
        if (!data.tag_no.trim()) return toast(a("tagNeeded"), true)
        const { error } = await db.from("lehengas").insert({
          tag_no: data.tag_no.trim(),
          title: data.title || "",
          photo,
        })
        if (error) return fail(error)
      } else {
        const payload = {
          title: data.title || "",
          status: data.status,
          client_name: data.client_name || "",
          client_phone: data.client_phone || "",
          event_date: data.event_date || null,
          paid_status: data.paid_status,
          amount_inr: numOrNull(data.amount_inr),
          note: data.note || "",
          updated_at: new Date().toISOString(),
        }
        if (photo) payload.photo = photo
        const { error } = await db.from("lehengas").update(payload).eq("id", form.dataset.id)
        if (error) return fail(error)
      }
    }
    if (kind === "gift-book") {
      const { data: created, error } = await db.from("gift_books").insert({
        client_name: data.client_name.trim(),
        event_date: data.event_date || null,
        note: data.note || "",
      }).select("id").single()
      if (error) return fail(error)
      activeBook = created.id
    }
    if (kind === "gift-new" || kind === "gift-line") {
      const total = Number(data.total_qty)
      const used = Number(data.used_qty)
      if (used > total) return toast(a("failed"), true)
      const payload = { product_name: data.product_name.trim(), total_qty: total, used_qty: used }
      const query = kind === "gift-new"
        ? db.from("gift_lines").insert({ ...payload, book_id: form.dataset.id })
        : db.from("gift_lines").update(payload).eq("id", form.dataset.id)
      const { error } = await query
      if (error) return fail(error)
    }
    if (kind === "trainee-new" || kind === "trainee-edit") {
      const fee = Number(data.fee_inr || 0)
      const paid = Number(data.paid_inr || 0)
      if (paid > fee) return toast(a("failed"), true)
      const payload = {
        full_name: data.full_name.trim(),
        age: data.age ? Number(data.age) : null,
        guardian_name: data.guardian_name || "",
        phone: data.phone || "",
        course: data.course.trim(),
        started_on: data.started_on,
        status: data.status || "learning",
        fee_inr: fee,
        paid_inr: paid,
        note: data.note || "",
        updated_at: new Date().toISOString(),
      }
      const query = kind === "trainee-new"
        ? db.from("trainees").insert(payload)
        : db.from("trainees").update(payload).eq("id", form.dataset.id)
      const { error } = await query
      if (error) return fail(error)
    }
    if (kind === "settings") {
      const { error } = await db.from("studio_settings").update({
        whatsapp: data.whatsapp.replace(/\D/g, ""),
        phone_main: data.phone_main.replace(/\D/g, ""),
        phone_booking: data.phone_booking.replace(/\D/g, ""),
        phone_extra: data.phone_extra.replace(/\D/g, ""),
        updated_at: new Date().toISOString(),
      }).eq("id", 1)
      if (error) return fail(error)
    }
    if (kind === "slot") {
      const { error } = await db.from("time_slots").update({
        label_hi: data.label_hi.trim(),
        label_en: data.label_en.trim(),
        starts: data.starts.trim(),
        ends: data.ends.trim(),
        active: form.querySelector('[name="active"]').checked,
      }).eq("id", form.dataset.id)
      if (error) return fail(error)
    }
    if (kind === "password") {
      if (data.password.length < 8) return toast(a("passwordShort"), true)
      const { error } = await db.auth.updateUser({ password: data.password })
      if (error) return fail(error)
      form.reset()
      toast(a("passwordOk"))
      return
    }
    toast(a("saved"))
    await loadCore()
    render()
  } catch (error) {
    fail(error)
  }
}

async function onClick(event) {
  const button = event.target.closest("[data-act]")
  if (!button) return
  const act = button.dataset.act
  try {
    if (act === "month") {
      cursor = new Date(cursor.getFullYear(), cursor.getMonth() + Number(button.dataset.dir), 1)
      await loadMonth()
      render()
    }
    if (act === "pick-day") {
      selected = button.dataset.date
      render()
    }
    if (act === "block") {
      const { error } = await db.from("slot_blocks").insert({ event_date: selected, slot: button.dataset.slot, note: "" })
      if (error) return fail(error)
      await loadMonth()
      render()
    }
    if (act === "unblock") {
      const { error } = await db.from("slot_blocks").delete().eq("id", button.dataset.id)
      if (error) return fail(error)
      await loadMonth()
      render()
    }
    if (act === "close-day") {
      for (const slot of slots.filter((item) => item.active)) {
        const busy = bookings.some((item) => item.event_date === selected && item.slot === slot.id && item.status !== "cancelled")
        const blocked = blocks.some((item) => item.event_date === selected && item.slot === slot.id)
        if (busy || blocked) continue
        await db.from("slot_blocks").insert({ event_date: selected, slot: slot.id, note: lang === "hi" ? "दिन बंद" : "Day closed" })
      }
      await loadMonth()
      render()
    }
    if (act === "open-day") {
      const ids = blocks.filter((item) => item.event_date === selected).map((item) => item.id)
      if (ids.length) await db.from("slot_blocks").delete().in("id", ids)
      await loadMonth()
      render()
    }
    if (act === "open-book") {
      activeBook = button.dataset.id
      render()
    }
    if (act === "delete-book") {
      await db.from("gift_books").delete().eq("id", button.dataset.id)
      activeBook = null
      await loadCore()
      render()
    }
    if (act === "delete-lehenga") {
      await db.from("lehengas").delete().eq("id", button.dataset.id)
      await loadCore()
      render()
    }
    if (act === "delete-trainee") {
      await db.from("trainees").delete().eq("id", button.dataset.id)
      await loadCore()
      render()
    }
    if (act === "wa-lehenga") {
      const item = lehengas.find((row) => row.id === button.dataset.id)
      if (!item) return
      const paid = item.paid_status === "paid" ? a("paidFull") : a(item.paid_status)
      const lines = [
        "Tanishq Makeover, ओराई",
        "लहंगा बुकिंग",
        `टैग: ${item.tag_no}`,
        item.title ? `नाम: ${item.title}` : "",
        `स्थिति: ${a(item.status)}`,
        item.client_name ? `ग्राहक: ${item.client_name}` : "",
        item.event_date ? `तिथि: ${item.event_date}` : "",
        `भुगतान: ${paid}`,
        item.amount_inr != null ? `राशि: ₹${item.amount_inr}` : "",
        item.note ? `टिप्पणी: ${item.note}` : "",
      ].filter(Boolean)
      const phone = String(item.client_phone || settings.whatsapp || "").replace(/\D/g, "")
      const number = phone.length === 10 ? `91${phone}` : phone
      window.open(`https://wa.me/${number}?text=${encodeURIComponent(lines.join("\n"))}`, "_blank", "noopener,noreferrer")
    }
  } catch (error) {
    fail(error)
  }
}

